import assert from 'node:assert/strict';
import {localClient} from './m0-test-client.mjs';
import {writePrivate} from './local-runtime.mjs';
const f=localClient(),checks=[];
const before=f.sql("select version||':'||(select count(*) from private.sectors)||':'||(select count(*) from private.catalog_snapshots) from private.catalog_head;");
f.sql(`begin;
do $$declare h bigint;parent uuid;leaf uuid;label text;v bigint;begin
select version into h from private.catalog_head;
label:='SYNTHETIC '||gen_random_uuid();
parent:=private.catalog_edit_sector('SECTOR_CREATE',null,jsonb_build_object('name',label,'catalog_kind','PARENT'),h);
leaf:=private.catalog_edit_sector('SECTOR_CREATE',null,jsonb_build_object('name',label||' leaf','catalog_kind','LEAF','parent_id',parent),h);
perform private.catalog_edit_sector('SECTOR_UPDATE',leaf,jsonb_build_object('description',E'첫 줄\n둘째 줄'),h);
if (select description from private.sectors where id=leaf)<>E'첫 줄\n둘째 줄' then raise exception 'DESCRIPTION_UPDATE_FAILED';end if;
begin perform private.catalog_edit_sector('SECTOR_CREATE',null,jsonb_build_object('name',label,'catalog_kind','PARENT'),h);raise exception 'EXPECTED_COLLISION';
exception when raise_exception then if sqlerrm<>'CATALOG_NAME_COLLISION' then raise;end if;end;
perform private.catalog_edit_sector('SECTOR_DEACTIVATE',parent,jsonb_build_object('impact_sha256',private.catalog_impact(parent)->>'impact_sha256'),h);
if exists(select 1 from private.sectors where id in(parent,leaf) and active) then raise exception 'PARENT_CASCADE_FAILED';end if;
begin perform private.catalog_edit_sector('SECTOR_RESTORE',leaf,'{}',h);raise exception 'EXPECTED_PARENT_REJECTION';
exception when raise_exception then if sqlerrm<>'INACTIVE_CATALOG_PARENT' then raise;end if;end;
perform private.catalog_edit_sector('SECTOR_RESTORE',parent,'{}',h);
if (select active from private.sectors where id=leaf) then raise exception 'IMPLICIT_CHILD_RESTORE';end if;
perform private.catalog_edit_sector('SECTOR_RESTORE',leaf,'{}',h);
v:=private.catalog_finish_version(h);
if v<=h or not private.catalog_sector_selectable(leaf,v,'SYNTHETIC') then raise exception 'NEW_SNAPSHOT_FAILED';end if;
end$$;
rollback;`);
assert.equal(f.sql("select version||':'||(select count(*) from private.sectors)||':'||(select count(*) from private.catalog_snapshots) from private.catalog_head;"),before);
for(const name of ['Create and description update preserve newlines','NFC name collision rejects duplicate identity','Parent deactivation cascades to child','Inactive parent blocks child restoration','Parent restoration does not reactivate child','Snapshot advance is valid and fixture transaction rolls back'])checks.push({name,status:'PASS'});
writePrivate('catalog-sector-mutation-tests.json',{status:'PASS',checks,fixtureTransactionRolledBack:true,realRequestsExecuted:0});
console.log(JSON.stringify({status:'PASS',checks}));
