// Real-data source hosts shared by the AI processor's intake mapping (runtime/publish-map.mjs) and the database
// (private.real_mode allowed/official hosts): DART and KIND plus every enabled company website (owner decision
// 2026-11-28). All are official Korean primary sources.
// Writes data/real-source-hosts.json, supabase/migrations/20261128000063_real_source_hosts.sql (local) and
// supabase/cloud/real-intake-dev/source-hosts.sql (cloud). Usage: node scripts/tools/real-source-hosts.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';

const root = new URL('../../', import.meta.url);
const read = p => readFileSync(new URL(p, root), 'utf8');
const HOST = /^[a-z0-9]([a-z0-9-]*[a-z0-9])?(\.[a-z0-9]([a-z0-9-]*[a-z0-9])?)+$/;
const config = JSON.parse(read('.local-data/ai/config.json'));
const company = config.sources.filter(s => s.kind === 'OFFICIAL' && s.status === 'ENABLED' && !s.revokedAt).map(s => s.host)
  .filter(h => !/(^|\.)dart\.fss\.or\.kr$/.test(h));
const hosts = ['dart.fss.or.kr', 'kind.krx.co.kr', ...[...new Set(company)].sort()];
for (const h of hosts) if (!HOST.test(h) || h.length > 253) throw new Error('bad host ' + h);
if (hosts.length > 1000) throw new Error('more than 1000 hosts');
writeFileSync(new URL('data/real-source-hosts.json', root), JSON.stringify({ version: 'real-source-hosts-20261128', decision: 'docs/context/DECISIONS.md 2026-11-28 기업 사이트 출처 전체 허가', hosts }, null, 1) + '\n');

const q = v => "'" + String(v).replaceAll("'", "''") + "'";
const arr = `array[${hosts.map(q).join(',')}]`;
// The newest guard definition of each environment, with only the host-count limit raised (20 -> 1000).
function guard(sqlText) {
  const start = sqlText.lastIndexOf('create or replace function private.real_mode_guard()');
  const end = sqlText.indexOf('end$$;', start);
  if (start < 0 || end < 0) throw new Error('guard not found');
  const body = sqlText.slice(start, end + 6);
  if (body.split('not between 1 and 20\n').length !== 2) throw new Error('limit not found exactly once');
  return body.replace('not between 1 and 20\n', 'not between 1 and 1000\n');
}
const localGuard = guard(read('supabase/migrations/20261127000059_real_public_read.sql'));
const cloudGuard = guard(read('supabase/cloud/real-intake-dev/apply.sql'));
const hostsMd5 = createHash('md5').update(hosts.join(','), 'utf8').digest('hex');
const post = code => `do $post$
begin
  if (select array_to_string(allowed_source_hosts,',') from private.real_mode where id=1) is distinct from ${q(hosts.join(','))}
    or (select array_to_string(official_source_hosts,',') from private.real_mode where id=1) is distinct from ${q(hosts.join(','))} then raise exception '${code}_POST_HOSTS';end if;
  if md5((select array_to_string(allowed_source_hosts,',') from private.real_mode where id=1)) is distinct from ${q(hostsMd5)} then raise exception '${code}_POST_DIGEST';end if;
  if private.public_read_kind()<>'SYNTHETIC' and not exists(select 1 from private.runtime_identity where environment='local') then raise exception '${code}_POST_KIND';end if;
end$post$;`;

writeFileSync(new URL('supabase/migrations/20261128000063_real_source_hosts.sql', root), `begin;
-- Real-data source hosts (owner decision 2026-11-28): DART, KIND and every enabled company website (press, newsroom,
-- IR) as official primary sources; the host-count limit rises from 20 to 1000. Generated by
-- scripts/tools/real-source-hosts.mjs from data/real-source-hosts.json (${hosts.length} hosts).
${localGuard}
update private.real_mode set allowed_source_hosts=${arr}, official_source_hosts=${arr} where id=1;
${post('SOURCE_HOSTS')}
commit;
`);

writeFileSync(new URL('supabase/cloud/real-intake-dev/source-hosts.sql', root), `-- CLOUD14 real-data source hosts for nxfpfvsdwbziowkxsxnh (generated by scripts/tools/real-source-hosts.mjs; do not edit).
-- Same change as local migration 63, with the cloud guard (CLOUD13 rendering: real mode in local or preview).
begin;
set local statement_timeout='30s';
select pg_advisory_xact_lock(hashtext('judoju-cloud-schema-change'));
do $guard$
begin
  if current_user<>'postgres' then raise exception 'CLOUD14_POSTGRES_REQUIRED';end if;
  if (select to_jsonb(x)->>'environment' from judoju_control.environment_identity x limit 1) is distinct from 'dev'
    or (select to_jsonb(x)->>'project_ref' from judoju_control.environment_identity x limit 1) is distinct from 'nxfpfvsdwbziowkxsxnh' then raise exception 'CLOUD14_ENVIRONMENT';end if;
  if (select jsonb_agg(version order by version) from supabase_migrations.schema_migrations)->-1 is distinct from '"20261128000108"'::jsonb then raise exception 'CLOUD14_MIGRATIONS';end if;
  if not exists(select 1 from pg_proc where oid='private.real_mode_guard()'::regprocedure and prosrc ~ 'not between 1 and 20[^0-9]') then raise exception 'CLOUD14_GUARD_DRIFT';end if;
end$guard$;
${cloudGuard}
update private.real_mode set allowed_source_hosts=${arr}, official_source_hosts=${arr} where id=1;
${post('CLOUD14')}
do $kind$ begin
  if not private.real_mode_on() or private.public_read_kind()<>'SYNTHETIC' then raise exception 'CLOUD14_POST_REAL_MODE';end if;
  if public.m1_public_identity() is distinct from '{"productId":"judoju-news","environment":"preview","sampleKind":"SYNTHETIC","bootstrapId":null,"contract":"M1"}'::jsonb then raise exception 'CLOUD14_POST_IDENTITY';end if;
end$kind$;
insert into supabase_migrations.schema_migrations(version,name,statements) values ('20261128000109','cloud14_real_source_hosts',array['supabase/cloud/real-intake-dev/source-hosts.sql hosts-md5=${hostsMd5} count=${hosts.length}']);
commit;
`);
console.log(JSON.stringify({ hosts: hosts.length, hostsMd5 }));
