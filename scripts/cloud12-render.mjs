// Renders supabase/cloud/company-scope-dev/apply.sql (CLOUD12A): local migrations 51-55 (company scope and page,
// sector sections, impact-company badges, hidden related sectors) for the cloud preview project, in one transaction:
// guard (identity, migration list, exact pre-51 definitions, nothing of 51-55 present) -> the five migrations
// verbatim (their own begin/commit removed) -> cloud ACL rule (public read functions are anon-only) -> migration
// record -> post-check (definitions equal the local ones, anon exactly the ten read functions, authenticated and
// service_role unchanged). Any mismatch raises and the whole transaction rolls back.
import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';

const root = new URL('../', import.meta.url);
const pre = JSON.parse(readFileSync(new URL('supabase/cloud/company-scope-dev/prestate.json', root), 'utf8'));
const q = value => "'" + String(value).replaceAll("'", "''") + "'";
const json = value => q(JSON.stringify(value)) + '::jsonb';
// New function -> the existing function whose ACL it must carry.
const aclFrom = {
  'private.m1_prepare(uuid,jsonb,bigint,bigint)': 'private.m1_prepare_v5(uuid,jsonb,bigint,bigint)',
  'private.m1_prepare_v7(uuid,jsonb,bigint,bigint)': 'private.m1_prepare_v5(uuid,jsonb,bigint,bigint)',
  'private.public_body(jsonb,text[],timestamptz)': 'private.public_body_v3(jsonb,text[],timestamptz)',
  'private.visible_sections(text,jsonb,timestamptz,timestamptz)': 'private.visible_sections_v2(text,jsonb,timestamptz,timestamptz)',
  'public.catalog_public_company(bigint,uuid,integer,timestamptz,timestamptz,uuid)': 'public.catalog_public_articles(bigint,uuid[],text,integer,timestamptz,timestamptz,uuid)'
};
const hash = k =>`encode(sha256(convert_to(pg_get_functiondef(${q(k)}::regprocedure),'UTF8')),'hex')`;

const bodies = pre.sources.map(path => {
  const text = readFileSync(new URL(path, root), 'utf8');
  if (text.includes('\r')) throw new Error('CRLF in ' + path);
  const lines = text.replace(/\n+$/, '').split('\n');
  if (lines[0] !== 'begin;' || lines.at(-1) !== 'commit;') throw new Error('Unexpected framing in ' + path);
  return { path, sql: lines.slice(1, -1).join('\n') };
});
for (const { sql, path } of bodies) if (/\b(begin|commit|rollback)\s*;/i.test(sql.replace(/\$\$[\s\S]*?\$\$/g, ''))) throw new Error('Nested transaction control in ' + path);

const acl = role => `select coalesce(jsonb_agg(n.nspname||'.'||p.proname order by n.nspname||'.'||p.proname),'[]') from pg_proc p join pg_namespace n on n.oid=p.pronamespace
    where n.nspname in ('public','private','judoju_control') and p.proname<>'rls_auto_enable' and has_function_privilege(${q(role)},p.oid,'EXECUTE')`;

const aclBlock = `do $acl$
declare r record;g record;
begin
  for r in select * from jsonb_each_text(${json(aclFrom)}) loop
    execute format('revoke all on function %s from public, anon, authenticated, service_role', r.key::regprocedure);
    for g in select a.grantee from pg_proc p, aclexplode(p.proacl) a where p.oid=r.value::regprocedure and a.grantee<>p.proowner and a.privilege_type='EXECUTE' loop
      if g.grantee=0 then execute format('grant execute on function %s to public', r.key::regprocedure);
      else execute format('grant execute on function %s to %I', r.key::regprocedure, (select rolname from pg_roles where oid=g.grantee));end if;
    end loop;
  end loop;
end$acl$`;
// The migration record holds exactly what ran: the five bodies and the cloud ACL step.
const recorded = [...bodies.map(b => b.sql), aclBlock];
const recordedMd5 = createHash('md5').update(recorded.join('\u0001'), 'utf8').digest('hex');

const sql = `-- CLOUD12A company scope for ${pre.projectRef} (generated by scripts/cloud12-render.mjs; do not edit by hand).
begin;
set local statement_timeout='60s';
set local lock_timeout='5s';
-- No concurrent migration or grant may land between the guard and commit.
select pg_advisory_xact_lock(hashtext('judoju-cloud-schema-change'));
lock table supabase_migrations.schema_migrations in exclusive mode;
create temp table cloud12_acl_before on commit drop as
  select (${acl('authenticated')}) as authenticated, (${acl('service_role')}) as service_role;
do $guard$
declare k text;v text;
begin
  if current_user<>'postgres' then raise exception 'CLOUD12_POSTGRES_REQUIRED';end if;
  if (select count(*) from judoju_control.environment_identity)<>1
    or (select to_jsonb(x)->>'environment' from judoju_control.environment_identity x) is distinct from 'dev'
    or (select to_jsonb(x)->>'project_ref' from judoju_control.environment_identity x) is distinct from ${q(pre.projectRef)} then raise exception 'CLOUD12_ENVIRONMENT';end if;
  if public.m1_public_identity() is distinct from '{"productId":"judoju-news","environment":"preview","sampleKind":"SYNTHETIC","bootstrapId":null,"contract":"M1"}'::jsonb then raise exception 'CLOUD12_IDENTITY';end if;
  if (select jsonb_agg(version order by version) from supabase_migrations.schema_migrations) is distinct from ${json(pre.migrations)} then raise exception 'CLOUD12_MIGRATIONS';end if;
  for k,v in select * from jsonb_each_text(${json(pre.beforeHashes)}) loop
    if encode(sha256(convert_to(pg_get_functiondef(k::regprocedure),'UTF8')),'hex') is distinct from v then raise exception 'CLOUD12_DEFINITION_DRIFT %',k;end if;
  end loop;
  for k in select value from jsonb_array_elements_text(${json(pre.mustNotExist)}) loop
    if exists(select 1 from pg_proc p join pg_namespace n on n.oid=p.pronamespace where n.nspname||'.'||p.proname=k) then raise exception 'CLOUD12_ALREADY_PRESENT %',k;end if;
  end loop;
end$guard$;

${bodies.map(({ path, sql }) => `-- ${path}\n${sql}`).join('\n\n')}

-- Cloud ACL: the cloud has no local default privileges, so each function created above takes exactly the ACL of the
-- function it replaces; the company page takes the ACL of the other public read functions (anon only).
${aclBlock};
insert into supabase_migrations.schema_migrations(version,name,statements) values (${q(pre.record.version)},${q(pre.record.name)},array[${recorded.map(q).join(',')}]);

do $post$
declare k text;v text;got jsonb;
begin
  for k,v in select * from jsonb_each_text(${json(pre.afterHashes)}) loop
    if encode(sha256(convert_to(pg_get_functiondef(k::regprocedure),'UTF8')),'hex') is distinct from v then raise exception 'CLOUD12_POST_DEFINITION %',k;end if;
  end loop;
  for k,v in select * from jsonb_each_text(${json(aclFrom)}) loop
    if (select coalesce(jsonb_agg(a.grantee::regrole::text||':'||a.privilege_type order by a.grantee::regrole::text||':'||a.privilege_type),'[]') from pg_proc p, aclexplode(p.proacl) a where p.oid=k::regprocedure and a.grantee<>0)
      is distinct from (select coalesce(jsonb_agg(a.grantee::regrole::text||':'||a.privilege_type order by a.grantee::regrole::text||':'||a.privilege_type),'[]') from pg_proc p, aclexplode(p.proacl) a where p.oid=v::regprocedure and a.grantee<>0)
      or exists(select 1 from pg_proc p, aclexplode(p.proacl) a where p.oid=k::regprocedure and a.grantee=0) is distinct from exists(select 1 from pg_proc p, aclexplode(p.proacl) a where p.oid=v::regprocedure and a.grantee=0)
      or (select proacl is null from pg_proc where oid=k::regprocedure) then raise exception 'CLOUD12_POST_ACL %',k;end if;
  end loop;
  ${acl('anon')} into got;
  if got is distinct from ${json(pre.anonReadAfter)} then raise exception 'CLOUD12_POST_ANON %',got;end if;
  if (${acl('authenticated')}) is distinct from (select authenticated from cloud12_acl_before) then raise exception 'CLOUD12_POST_AUTHENTICATED';end if;
  if (${acl('service_role')}) is distinct from (select service_role from cloud12_acl_before) then raise exception 'CLOUD12_POST_SERVICE_ROLE';end if;
  if (select jsonb_agg(version order by version) from supabase_migrations.schema_migrations) is distinct from ${json([...pre.migrations, pre.record.version])} then raise exception 'CLOUD12_POST_MIGRATIONS';end if;
  if (select count(*) from supabase_migrations.schema_migrations where version=${q(pre.record.version)} and name=${q(pre.record.name)}
      and cardinality(statements)=${recorded.length} and md5(array_to_string(statements,chr(1)))=${q(recordedMd5)})<>1 then raise exception 'CLOUD12_POST_RECORD';end if;
end$post$;
notify pgrst,'reload schema';
commit;
`;
const out = new URL('supabase/cloud/company-scope-dev/apply.sql', root);
writeFileSync(out, sql);
console.log(JSON.stringify({ written: 'supabase/cloud/company-scope-dev/apply.sql', sha256: createHash('sha256').update(sql).digest('hex'), bytes: Buffer.byteLength(sql) }));
