// Renders supabase/cloud/admin-online-dev/activation.sql from the pinned prestate and core.sql.
// One transaction: guard (identity, migrations, definition hashes, tables, owner, no grants) -> core hardening ->
// owner role, membership and the fixed EXECUTE grants -> post-check of the resulting API ACL. Any mismatch raises
// before or after the change and the whole transaction rolls back.
import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';

const root = new URL('../supabase/cloud/admin-online-dev/', import.meta.url);
const pre = JSON.parse(readFileSync(new URL('prestate.json', root), 'utf8'));
const core = readFileSync(new URL('core.sql', root), 'utf8');
const q = value => "'" + String(value).replaceAll("'", "''") + "'";
const json = value => q(JSON.stringify(value)) + '::jsonb';
const editors = Object.keys(pre.editorHashes), sessions = ['public.m1_open_admin_session(uuid,uuid,text,text,timestamptz)', 'public.m1_read_admin_session(text)', 'public.m1_close_admin_session(text)'];
const readRpcs = ['public.catalog_public_articles', 'public.catalog_public_company_sectors', 'public.catalog_public_saved', 'public.catalog_public_search_companies',
  'public.catalog_public_search_news', 'public.catalog_public_sector_page', 'public.catalog_public_tree', 'public.m1_public_article', 'public.m1_public_identity'];
const hashes = { ...pre.helperHashes, ...pre.editorHashes };

const sql = `-- CLOUD11-online activation for ${pre.projectRef} (generated by scripts/cloud11-online-render.mjs; do not edit by hand).
begin;
set local statement_timeout='30s';
set local lock_timeout='5s';
do $guard$
declare k text;v text;got text;
begin
  if current_user<>'postgres' then raise exception 'CLOUD11_POSTGRES_REQUIRED';end if;
  if (select to_jsonb(x)->>'environment' from judoju_control.environment_identity x limit 1)<>'dev'
    or (select to_jsonb(x)->>'project_ref' from judoju_control.environment_identity x limit 1)<>${q(pre.projectRef)} then raise exception 'CLOUD11_ENVIRONMENT';end if;
  if public.m1_public_identity()<>'{"productId":"judoju-news","environment":"preview","sampleKind":"SYNTHETIC","bootstrapId":null,"contract":"M1"}'::jsonb then raise exception 'CLOUD11_IDENTITY';end if;
  if (select jsonb_agg(version order by version) from supabase_migrations.schema_migrations)<>${json(pre.migrations)} then raise exception 'CLOUD11_MIGRATIONS';end if;
  for k,v in select * from jsonb_each_text(${json(hashes)}) loop
    got:=encode(sha256(convert_to(pg_get_functiondef(k::regprocedure),'UTF8')),'hex');
    if got is distinct from v then raise exception 'CLOUD11_DEFINITION_DRIFT %',k;end if;
  end loop;
  if (select jsonb_agg(conname||':'||pg_get_constraintdef(oid) order by conname) from pg_constraint where conrelid='private.admin_sessions'::regclass)<>${json(pre.tables['private.admin_sessions'].constraints)}
    or (select jsonb_agg(conname||':'||pg_get_constraintdef(oid) order by conname) from pg_constraint where conrelid='private.admin_memberships'::regclass)<>${json(pre.tables['private.admin_memberships'].constraints)}
    or not (select relrowsecurity from pg_class where oid='private.admin_sessions'::regclass) or not (select relrowsecurity from pg_class where oid='private.admin_memberships'::regclass)
    then raise exception 'CLOUD11_TABLE_DRIFT';end if;
  if (select count(*) from private.admin_memberships)<>0 or (select count(*) from private.admin_sessions)<>0 then raise exception 'CLOUD11_NOT_EMPTY';end if;
  if not exists(select 1 from auth.users where id=${q(pre.ownerUserId)} and deleted_at is null and not is_sso_user and email_confirmed_at is not null and coalesce(encrypted_password,'')<>'')
    then raise exception 'CLOUD11_OWNER';end if;
  for k in select value from jsonb_array_elements_text(${json([...editors, ...sessions])}) loop
    if has_function_privilege('anon',k,'EXECUTE') or has_function_privilege('authenticated',k,'EXECUTE') or has_function_privilege('service_role',k,'EXECUTE') then raise exception 'CLOUD11_ALREADY_GRANTED %',k;end if;
  end loop;
end$guard$;

${core}
update auth.users set raw_app_meta_data=coalesce(raw_app_meta_data,'{}'::jsonb)||'{"app_role":"admin","product_id":"judoju-news"}'::jsonb where id=${q(pre.ownerUserId)};
insert into private.admin_memberships(user_id,active) values (${q(pre.ownerUserId)},true);
grant execute on function ${editors.join(',')} to authenticated;
grant execute on function ${sessions.join(',')} to service_role;
insert into private.audits(actor_id,action,entity_id) values('system','ADMIN_ONLINE_ACTIVATE',${q(pre.ownerUserId)});

do $post$
declare got jsonb;
begin
  -- authenticated may execute exactly the 21 editor functions (plus Supabase's managed rls_auto_enable).
  select coalesce(jsonb_agg(p.oid::regprocedure::text order by p.oid::regprocedure::text),'[]') into got from pg_proc p join pg_namespace n on n.oid=p.pronamespace
    where n.nspname='public' and p.proname<>'rls_auto_enable' and has_function_privilege('authenticated',p.oid,'EXECUTE');
  if got<>(select jsonb_agg(x order by x) from jsonb_array_elements_text(${json(editors.map(name => name.replace(/^public\./, '')))}) x) then raise exception 'CLOUD11_POST_AUTHENTICATED %',got;end if;
  -- anon keeps exactly the nine public read RPCs.
  select coalesce(jsonb_agg(n.nspname||'.'||p.proname order by p.proname),'[]') into got from pg_proc p join pg_namespace n on n.oid=p.pronamespace
    where n.nspname in ('public','private','judoju_control') and p.proname<>'rls_auto_enable' and has_function_privilege('anon',p.oid,'EXECUTE');
  if got<>${json(readRpcs)} then raise exception 'CLOUD11_POST_ANON %',got;end if;
  if not (has_function_privilege('service_role','public.m1_open_admin_session(uuid,uuid,text,text,timestamptz)','EXECUTE') and has_function_privilege('service_role','public.m1_read_admin_session(text)','EXECUTE')
    and has_function_privilege('service_role','public.m1_close_admin_session(text)','EXECUTE') and has_function_privilege('service_role','public.admin_online_revoke()','EXECUTE'))
    or has_function_privilege('authenticated','public.admin_online_revoke()','EXECUTE') or has_function_privilege('anon','public.admin_online_revoke()','EXECUTE') then raise exception 'CLOUD11_POST_SERVICE';end if;
  if (select count(*) from private.admin_memberships where active)<>1 or (select raw_app_meta_data->>'app_role' from auth.users where id=${q(pre.ownerUserId)})<>'admin' then raise exception 'CLOUD11_POST_OWNER';end if;
  if (select provolatile from pg_proc where oid='private.is_admin()'::regprocedure)<>'v' then raise exception 'CLOUD11_POST_IS_ADMIN';end if;
end$post$;
notify pgrst,'reload schema';
commit;
`;
writeFileSync(new URL('activation.sql', root), sql);
console.log(JSON.stringify({ written: 'supabase/cloud/admin-online-dev/activation.sql', sha256: createHash('sha256').update(sql).digest('hex'), editors: editors.length, sessions: sessions.length }));
