// Renders supabase/cloud/admin-online-dev/adopt-grant.sql (publish stage 2A S7): after CLOUD13, one transaction that
// installs the 22-function emergency status and revoke (from core.sql), grants the adoption function to editors only
// while the online admin is active (21 editor grants), and proves inside a rolled-back sub-block that the emergency
// revoke also removes the adoption grant.
import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';

const root = new URL('../supabase/cloud/admin-online-dev/', import.meta.url);
const core = readFileSync(new URL('core.sql', root), 'utf8');
const take = name => {
  const start = core.indexOf(`create or replace function public.${name}()`);
  const end = core.indexOf('end$$;', start);
  if (start < 0 || end < 0 || core.indexOf(`create or replace function public.${name}()`, start + 1) >= 0) throw new Error('core.sql: ' + name);
  return core.slice(start, end + 'end$$;'.length);
};
const ADOPT = 'public.m1_adopt_ai_version(uuid,integer,bigint,text)';
export function render() {
  return `-- CLOUD13 S7: online admin adoption grant (generated by scripts/cloud13-admin-render.mjs; do not edit by hand).
begin;
set local statement_timeout='30s';
do $guard$
begin
  if current_user<>'postgres' then raise exception 'ADOPT_POSTGRES_REQUIRED';end if;
  if (select to_jsonb(x)->>'environment' from judoju_control.environment_identity x limit 1) is distinct from 'dev'
    or (select to_jsonb(x)->>'project_ref' from judoju_control.environment_identity x limit 1) is distinct from 'nxfpfvsdwbziowkxsxnh' then raise exception 'ADOPT_ENVIRONMENT';end if;
  if not exists(select 1 from supabase_migrations.schema_migrations where version='20261128000108') then raise exception 'ADOPT_CLOUD13_REQUIRED';end if;
  if to_regprocedure('${ADOPT}') is null then raise exception 'ADOPT_FUNCTION_MISSING';end if;
  if has_function_privilege('anon','${ADOPT}','EXECUTE') or has_function_privilege('authenticated','${ADOPT}','EXECUTE') or has_function_privilege('service_role','${ADOPT}','EXECUTE')
    then raise exception 'ADOPT_ALREADY_GRANTED';end if;
end$guard$;

${take('admin_online_status')}

${take('admin_online_revoke')}

revoke all on function public.admin_online_status() from public,anon,authenticated;
grant execute on function public.admin_online_status() to service_role;
revoke all on function public.admin_online_revoke() from public,anon,authenticated;
grant execute on function public.admin_online_revoke() to service_role;

-- Grant only while the online admin is active (all 21 editor grants present); after an emergency revoke it stays off
-- until re-activation (activation.sql grants all 22).
do $grant$
begin
  if (public.admin_online_status()->>'editorGrants')::int=21 then
    execute 'grant execute on function ${ADOPT} to authenticated';
  elsif (public.admin_online_status()->>'editorGrants')::int<>0 then raise exception 'ADOPT_PARTIAL_EDITOR_GRANTS';
  end if;
end$grant$;

do $post$
declare active boolean:=(public.admin_online_status()->>'editorGrants')::int=22;
begin
  if not active and (public.admin_online_status()->>'editorGrants')::int<>0 then raise exception 'ADOPT_POST_GRANTS';end if;
  if has_function_privilege('authenticated','${ADOPT}','EXECUTE') is distinct from active then raise exception 'ADOPT_POST_AUTHENTICATED';end if;
  if has_function_privilege('anon','${ADOPT}','EXECUTE') or has_function_privilege('service_role','${ADOPT}','EXECUTE') then raise exception 'ADOPT_POST_OTHER_ROLES';end if;
  -- The emergency revoke covers the adoption grant (proved, then undone by the sub-block's exception).
  begin
    perform public.admin_online_revoke();
    if has_function_privilege('authenticated','${ADOPT}','EXECUTE') or (public.admin_online_status()->>'editorGrants')::int<>0 then raise exception 'ADOPT_POST_REVOKE_INCOMPLETE';end if;
    raise exception 'ADOPT_REVOKE_PROBE_OK';
  exception when raise_exception then
    if sqlerrm<>'ADOPT_REVOKE_PROBE_OK' then raise;end if;
  end;
  if has_function_privilege('authenticated','${ADOPT}','EXECUTE') is distinct from active then raise exception 'ADOPT_POST_PROBE_UNDONE';end if;
end$post$;
notify pgrst,'reload schema';
commit;
`;
}
if (process.argv[1]?.replaceAll('\\', '/').endsWith('scripts/cloud13-admin-render.mjs')) {
  const sql = render();
  writeFileSync(new URL('adopt-grant.sql', root), sql);
  console.log(JSON.stringify({ written: 'supabase/cloud/admin-online-dev/adopt-grant.sql', sha256: createHash('sha256').update(sql).digest('hex'), bytes: Buffer.byteLength(sql) }));
}
